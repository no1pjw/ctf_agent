#!/usr/bin/env bash
set -euo pipefail

usage() {
  cat <<'EOF'
usage:
  web-runtime.sh up --input DIR --work DIR --project NAME --image IMAGE [--port N]
  web-runtime.sh down --state FILE

Starts only a copied local CTF web service. Compose takes precedence over a
standalone Dockerfile. Runtime ports are rebound to loopback and Compose
networks are marked internal before startup.
EOF
}

[[ $# -ge 1 ]] || { usage >&2; exit 64; }
action=$1
shift

compose_command() {
  if docker compose version >/dev/null 2>&1; then
    printf 'docker compose\n'
  elif command -v docker-compose >/dev/null 2>&1 && docker-compose version >/dev/null 2>&1; then
    printf 'docker-compose\n'
  else
    return 1
  fi
}

write_env() {
  printf '%s=%q\n' "$1" "$2"
}

runtime_down() {
  local state_file=$1
  [[ -f "$state_file" ]] || return 0
  local runtime_mode= compose_project= compose_runtime_file= container_name= network_name= image_ref= service_copy=
  # Generated by this script with shell-safe values.
  # shellcheck disable=SC1090
  source "$state_file"
  case "${runtime_mode:-}" in
    compose)
      if [[ -n "${compose_runtime_file:-}" && -f "$compose_runtime_file" && -n "${compose_project:-}" ]]; then
        if compose_line=$(compose_command); then
          read -r -a compose_cmd <<< "$compose_line"
          "${compose_cmd[@]}" -f "$compose_runtime_file" -p "$compose_project" \
            down --volumes --remove-orphans --rmi local >/dev/null 2>&1 || true
        fi
      fi
      ;;
    dockerfile)
      [[ -z "${container_name:-}" ]] || docker rm -f "$container_name" >/dev/null 2>&1 || true
      [[ -z "${network_name:-}" ]] || docker network rm "$network_name" >/dev/null 2>&1 || true
      [[ -z "${image_ref:-}" ]] || docker image rm "$image_ref" >/dev/null 2>&1 || true
      ;;
  esac
  if [[ -n "${service_copy:-}" && -d "$service_copy" ]]; then
    case "$service_copy" in
      */work/service) rm -rf -- "$service_copy" ;;
      *) printf 'refusing to remove unexpected service copy: %s\n' "$service_copy" >&2 ;;
    esac
  fi
}

if [[ "$action" == down ]]; then
  state_file=
  while [[ $# -gt 0 ]]; do
    case "$1" in
      --state) state_file=${2:-}; shift 2 ;;
      -h|--help) usage; exit 0 ;;
      *) printf 'unknown down option: %s\n' "$1" >&2; exit 64 ;;
    esac
  done
  [[ -n "$state_file" ]] || { usage >&2; exit 64; }
  runtime_down "$state_file"
  exit 0
fi

[[ "$action" == up ]] || { usage >&2; exit 64; }
input_dir=
work_dir=
project=
image_ref=
container_port=
while [[ $# -gt 0 ]]; do
  case "$1" in
    --input) input_dir=${2:-}; shift 2 ;;
    --work) work_dir=${2:-}; shift 2 ;;
    --project) project=${2:-}; shift 2 ;;
    --image) image_ref=${2:-}; shift 2 ;;
    --port) container_port=${2:-}; shift 2 ;;
    -h|--help) usage; exit 0 ;;
    *) printf 'unknown up option: %s\n' "$1" >&2; exit 64 ;;
  esac
done

[[ -d "$input_dir" && -n "$work_dir" && -n "$project" && -n "$image_ref" ]] || { usage >&2; exit 64; }
[[ "$project" =~ ^[a-z0-9][a-z0-9_-]*$ ]] || { printf 'invalid project name: %s\n' "$project" >&2; exit 65; }
if [[ -n "$container_port" ]]; then
  [[ "$container_port" =~ ^[0-9]+$ ]] && (( container_port >= 1 && container_port <= 65535 )) || {
    printf 'port must be 1..65535: %s\n' "$container_port" >&2
    exit 65
  }
fi
command -v docker >/dev/null 2>&1 || { echo 'docker CLI is required' >&2; exit 69; }
command -v python3 >/dev/null 2>&1 || { echo 'python3 is required' >&2; exit 69; }
docker info >/dev/null 2>&1 || { echo 'docker daemon is unavailable' >&2; exit 69; }

input_real=$(readlink -f -- "$input_dir")
mkdir -p "$work_dir"
work_real=$(readlink -f -- "$work_dir")
state_file="$work_real/web-runtime.env"
log_file="$work_real/web-runtime.log"
service_copy="$work_real/service"

if [[ -f "$state_file" ]]; then
  runtime_down "$state_file"
  rm -f -- "$state_file"
fi
rm -rf -- "$service_copy"
mkdir -p "$service_copy"
cp -a -- "$input_real"/. "$service_copy"/
: > "$log_file"

compose_file=
for candidate in compose.yaml compose.yml docker-compose.yml docker-compose.yaml; do
  if [[ -f "$service_copy/$candidate" ]]; then
    compose_file="$service_copy/$candidate"
    break
  fi
done

runtime_mode=
endpoint=
all_endpoints=
compose_runtime_file=
container_name=
network_name=
cleanup_needed=true

cleanup_failure() {
  local status=$?
  trap - EXIT INT TERM HUP
  if [[ "$cleanup_needed" == true ]]; then
    if [[ "$runtime_mode" == compose && -n "$compose_runtime_file" && -f "$compose_runtime_file" ]]; then
      if compose_line=$(compose_command); then
        read -r -a compose_cmd <<< "$compose_line"
        "${compose_cmd[@]}" -f "$compose_runtime_file" -p "$project" down --volumes --remove-orphans --rmi local >/dev/null 2>&1 || true
      fi
    fi
    [[ -z "$container_name" ]] || docker rm -f "$container_name" >/dev/null 2>&1 || true
    [[ -z "$network_name" ]] || docker network rm "$network_name" >/dev/null 2>&1 || true
  fi
  exit "$status"
}
trap cleanup_failure EXIT
trap 'exit 130' INT
trap 'exit 143' TERM
trap 'exit 129' HUP

if [[ -n "$compose_file" ]]; then
  compose_line=$(compose_command) || {
    echo 'Docker Compose v2 is required for the supplied compose file.' >&2
    exit 69
  }
  read -r -a compose_cmd <<< "$compose_line"
  raw_config="$work_real/compose.resolved.json"
  compose_runtime_file="$work_real/compose.runtime.json"
  "${compose_cmd[@]}" -f "$compose_file" --project-directory "$service_copy" config --format json > "$raw_config"
  python3 - "$raw_config" "$compose_runtime_file" "$service_copy" <<'PY'
import json
import os
import sys

source, output, root = sys.argv[1:]
root = os.path.realpath(root)
with open(source, encoding="utf-8") as stream:
    config = json.load(stream)

services = config.get("services") or {}
if not services:
    raise SystemExit("compose config contains no services")

for name, service in services.items():
    if service.get("privileged"):
        raise SystemExit(f"unsafe compose service {name}: privileged=true")
    if service.get("network_mode") == "host" or service.get("pid") == "host" or service.get("ipc") == "host":
        raise SystemExit(f"unsafe compose service {name}: host namespace requested")
    if service.get("devices"):
        raise SystemExit(f"unsafe compose service {name}: device access requested")
    for volume in service.get("volumes") or []:
        if isinstance(volume, dict) and volume.get("type") == "bind":
            path = os.path.realpath(volume.get("source") or "")
            if os.path.commonpath([root, path]) != root:
                raise SystemExit(f"unsafe compose service {name}: bind mount leaves challenge copy: {path}")
    ports = service.get("ports") or []
    normalized = []
    for port in ports:
        if not isinstance(port, dict) or not port.get("target"):
            raise SystemExit(f"unsupported compose port form in {name}")
        port["host_ip"] = "127.0.0.1"
        port["published"] = "0"
        normalized.append(port)
    if not normalized and service.get("expose"):
        target = str(service["expose"][0]).split("/")[0]
        normalized.append({"target": int(target), "published": "0", "host_ip": "127.0.0.1", "protocol": "tcp"})
    service["ports"] = normalized
    caps = list(service.get("cap_drop") or [])
    if "ALL" not in caps:
        caps.append("ALL")
    service["cap_drop"] = caps
    security = list(service.get("security_opt") or [])
    if "no-new-privileges:true" not in security:
        security.append("no-new-privileges:true")
    service["security_opt"] = security
    service.setdefault("pids_limit", 256)

networks = config.setdefault("networks", {})
if not networks:
    networks["default"] = {}
for name, network in networks.items():
    if network.get("external"):
        raise SystemExit(f"unsafe compose network {name}: external network requested")
    network["internal"] = True

config.pop("name", None)
with open(output, "w", encoding="utf-8") as stream:
    json.dump(config, stream, ensure_ascii=False, indent=2)
    stream.write("\n")
PY
  runtime_mode=compose
  "${compose_cmd[@]}" -f "$compose_runtime_file" -p "$project" up --build -d --remove-orphans >> "$log_file" 2>&1
  mapfile -t container_ids < <("${compose_cmd[@]}" -f "$compose_runtime_file" -p "$project" ps -q)
  if (( ${#container_ids[@]} > 0 )); then
    mapfile -t endpoints < <(docker inspect "${container_ids[@]}" | python3 -c '
import json, sys
seen=set()
for container in json.load(sys.stdin):
    for bindings in (container.get("NetworkSettings", {}).get("Ports") or {}).values():
        for binding in bindings or []:
            port=binding.get("HostPort")
            if port and port not in seen:
                seen.add(port); print(f"http://127.0.0.1:{port}")
')
  else
    endpoints=()
  fi
  if (( ${#endpoints[@]} > 0 )); then
    endpoint=${endpoints[0]}
    all_endpoints=$(IFS=,; printf '%s' "${endpoints[*]}")
  fi
elif [[ -f "$service_copy/Dockerfile" ]]; then
  runtime_mode=dockerfile
  script_dir=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
  "$script_dir/pwn-build.sh" "$service_copy" "$image_ref" >> "$log_file" 2>&1
  if [[ -z "$container_port" ]]; then
    container_port=$(docker image inspect "$image_ref" --format '{{json .Config.ExposedPorts}}' | python3 -c '
import json, sys
ports=json.load(sys.stdin) or {}
tcp=sorted(int(key.split("/")[0]) for key in ports if key.endswith("/tcp"))
print(tcp[0] if tcp else "")
')
  fi
  [[ -n "$container_port" ]] || {
    echo 'Dockerfile has no EXPOSE port; rerun ctf-web with --port PORT.' >&2
    exit 68
  }
  network_name="${project}_internal"
  container_name="${project}_app"
  docker network create --internal "$network_name" >> "$log_file" 2>&1
  docker run -d --name "$container_name" --network "$network_name" \
    --publish "127.0.0.1::${container_port}" \
    --cap-drop ALL --cap-add NET_BIND_SERVICE --security-opt no-new-privileges \
    --pids-limit 256 --memory 1g --cpus 2 \
    "$image_ref" >> "$log_file" 2>&1
  host_binding=$(docker port "$container_name" "${container_port}/tcp" | sed -n '1p')
  host_port=${host_binding##*:}
  [[ "$host_port" =~ ^[0-9]+$ ]] || { echo 'failed to discover published web port' >&2; exit 70; }
  endpoint="http://127.0.0.1:$host_port"
  all_endpoints=$endpoint
else
  echo 'No compose.yaml, compose.yml, docker-compose.yml, docker-compose.yaml, or Dockerfile was found.' >&2
  exit 67
fi

[[ -n "$endpoint" ]] || {
  echo 'The Web runtime exposed no loopback HTTP endpoint.' >&2
  exit 70
}
python3 - "$endpoint" <<'PY'
import sys, time
from urllib.error import HTTPError
from urllib.request import HTTPRedirectHandler, build_opener

class NoRedirect(HTTPRedirectHandler):
    def redirect_request(self, req, fp, code, msg, headers, newurl):
        return None

url = sys.argv[1]
opener = build_opener(NoRedirect)
deadline = time.monotonic() + 30
last = None
while time.monotonic() < deadline:
    try:
        with opener.open(url, timeout=2) as response:
            response.read(1)
        break
    except HTTPError:
        break
    except Exception as exc:
        last = exc
        time.sleep(0.25)
else:
    raise SystemExit(f"Web runtime did not become ready within 30s: {last}")
PY

{
  write_env runtime_status running
  write_env runtime_mode "$runtime_mode"
  write_env endpoint "$endpoint"
  write_env all_endpoints "$all_endpoints"
  write_env compose_project "$project"
  write_env compose_runtime_file "$compose_runtime_file"
  write_env container_name "$container_name"
  write_env network_name "$network_name"
  write_env image_ref "$image_ref"
  write_env service_copy "$service_copy"
  write_env log_file "$log_file"
} > "$state_file"

cleanup_needed=false
trap - EXIT INT TERM HUP
printf 'web_runtime_status=running\n'
printf 'web_runtime_mode=%s\n' "$runtime_mode"
printf 'web_runtime_endpoint=%s\n' "${endpoint:-internal-compose-only}"
printf 'web_runtime_state=%s\n' "$state_file"
